// The PostgreSQL adapter (src/postgres.js): its SQL translation, configuration and search
// query building run everywhere; what needs a server runs with TEST_DATABASE_URL set (see
// fixture.js), and CI's PostgreSQL job sets REQUIRE_POSTGRES so it can't quietly skip.
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, before, test } from 'node:test';
import {
  PostgresDatabase, connectionString, databaseUrl, describeUrl, highlightTitle, loadDriver, param, statements, translate, tsQuery,
} from '../src/postgres.js';
import { TEST_DATABASE_URL, onPostgres, testDatabase } from './fixture.js';

const live = onPostgres ? false : 'needs PostgreSQL (TEST_DATABASE_URL)';

test('in CI\'s PostgreSQL job, the driver loads and these tests run against PostgreSQL', { skip: !process.env.REQUIRE_POSTGRES }, () => {
  assert.equal(onPostgres, true);
  assert.equal(typeof loadDriver(), 'function');
});

test('translation: placeholders, never inside quotes', () => {
  assert.equal(translate("SELECT * FROM t WHERE a = ? AND b = '?' AND c = \"we?ird\" AND d = ?"),
    "SELECT * FROM t WHERE a = $1 AND b = '?' AND c = \"we?ird\" AND d = $2");
  assert.equal(translate("SELECT 'it''s ?' AS x, ? AS y"), "SELECT 'it''s ?' AS x, $1 AS y");
  assert.deepEqual(statements("CREATE TABLE a (x TEXT); -- a comment; with semicolons\nINSERT INTO a VALUES (';');"),
    ['CREATE TABLE a (x TEXT)', "INSERT INTO a VALUES (';')"]);
});

test('translation: SQLite forms Store uses become PostgreSQL ones', () => {
  assert.equal(translate('INSERT OR IGNORE INTO tags (artifact_id, tag) VALUES (?, ?)'),
    'INSERT INTO tags (artifact_id, tag) VALUES ($1, $2) ON CONFLICT DO NOTHING');
  assert.equal(translate("SELECT date(x.at, 'unixepoch', 'localtime') AS day, group_concat(t.tag, ',') AS tags FROM x"),
    "SELECT to_char(to_timestamp(x.at), 'YYYY-MM-DD') AS day, string_agg(t.tag, ',') AS tags FROM x");
  assert.equal(translate("SELECT instr(a, '/'), char(1) FROM t"), "SELECT strpos(a, '/'), chr(1) FROM t");
  assert.equal(translate('PRAGMA foreign_keys = ON'), '');
  assert.match(translate('PRAGMA table_info(versions)'), /FROM information_schema\.columns WHERE .*table_name = 'versions'/);
  for (const sql of ['PRAGMA integrity_check', 'SELECT rowid FROM artifacts_fts WHERE artifacts_fts MATCH ?', "SELECT 1 FROM sqlite_master"]) {
    assert.throws(() => translate(sql), /unsupported in the PostgreSQL adapter/, sql);
  }
});

test('translation: column types, identity ids, and SQLite\'s byte-by-byte text comparison', () => {
  const ddl = translate(`CREATE TABLE IF NOT EXISTS widgets (
    id INTEGER PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users(id),
    name TEXT NOT NULL COLLATE NOCASE,
    note TEXT NOT NULL DEFAULT '',
    data BLOB NOT NULL,
    at REAL NOT NULL
  )`);
  assert.match(ddl, /id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(ddl, /owner_id INTEGER NOT NULL/);
  assert.match(ddl, /name TEXT NOT NULL COLLATE NOCASE/); // the database's case-insensitive ICU collation
  assert.match(ddl, /note TEXT COLLATE "C" NOT NULL DEFAULT ''/);
  assert.match(ddl, /data BYTEA NOT NULL/);
  assert.match(ddl, /at DOUBLE PRECISION NOT NULL/); // never 4-byte REAL: Unix times need more
  assert.equal(translate('INSERT INTO widgets (name) VALUES (?)'), 'INSERT INTO widgets (name) VALUES ($1) RETURNING id');
  assert.equal(translate('INSERT INTO tags (artifact_id, tag) VALUES (?, ?)'), 'INSERT INTO tags (artifact_id, tag) VALUES ($1, $2)'); // no id column
  assert.match(translate("ALTER TABLE artifacts ADD COLUMN pinned_at REAL"), /pinned_at DOUBLE PRECISION/);
});

test('configuration: DATABASE_URL is checked, its encoding kept, a timeout added only when missing, and never shown', () => {
  assert.equal(databaseUrl({}), null);
  assert.throws(() => databaseUrl({ DATABASE_URL: '  ' }), /DATABASE_URL is set but empty/);
  assert.throws(() => databaseUrl({ DATABASE_URL: 'mysql://u:secret@h/db' }), (e) => /postgres:\/\//.test(e.message) && !/secret/.test(e.message));
  assert.equal(databaseUrl({ DATABASE_URL: 'postgresql://h/db' }), 'postgresql://h/db');
  assert.equal(connectionString('postgres://u:p%40ss@h/db?sslmode=require&options=-c%20search_path%3Dx'),
    'postgres://u:p%40ss@h/db?sslmode=require&options=-c%20search_path%3Dx&connect_timeout=10');
  assert.equal(connectionString('postgres://h/db'), 'postgres://h/db?connect_timeout=10');
  assert.equal(connectionString('postgres://h/db?CONNECT_TIMEOUT=3'), 'postgres://h/db?CONNECT_TIMEOUT=3');
  assert.equal(describeUrl('postgresql://someone:hunter2@db.example.com:5433/pages?sslmode=require'), 'PostgreSQL db.example.com:5433/pages');
  assert.equal(describeUrl('postgres:///pages?host=/var/run/postgresql'), 'PostgreSQL /var/run/postgresql/pages');
});

test('values: NUL in text is refused (libpq would cut it off), binary is sent byte for byte', () => {
  assert.throws(() => param('a\0b'), (e) => e.status === 400 && /NUL/.test(e.message));
  assert.equal(param(Buffer.from([0, 1, 255])), '\\x0001ff');
  assert.equal(param(true), 1);
  assert.equal(param(undefined), null);
});

test('search: the words of a query as a tsquery, folded as the index folds them', () => {
  const words = [{ word: 'café', also: ['cafes'] }, { word: 'foo_bar', also: [] }];
  assert.equal(tsQuery(words), "('cafe':* | 'cafes') & ('foo' <-> 'bar':*)");
  assert.equal(tsQuery(words, { exact: true, weight: 'A' }), "('cafe':*A) & ('foo':A <-> 'bar':*A)");
  assert.equal(tsQuery([{ word: '___', also: [] }]), null); // nothing to look for
  const marked = highlightTitle('Crème brûlée at the Café', [{ word: 'creme', also: [] }, { word: 'cafe', also: [] }]);
  assert.equal(marked, '\u0001Crème\u0002 brûlée at the \u0001Café\u0002');
});

test('a failed connection is closed before its error goes on', async () => {
  let ended = 0;
  class Refused {
    connectSync() { throw new Error('connection refused'); }
    end(cb) { ended++; setImmediate(cb); }
  }
  assert.throws(() => PostgresDatabase.open('postgres://nowhere.invalid/x', { Client: Refused, types: { getTypeParser: () => String } }), /connection refused/);
  await new Promise((r) => setTimeout(r, 10));
  assert.equal(ended, 1);
});

test('a lost connection: the next query connects again; a read that found it gone runs again, a write does not', async () => {
  const clients = [];
  class Flaky { // a connection that can drop, as a database restart or an idle timeout drops one
    constructor() {
      this.n = clients.push(this);
      this.down = false;
      this.pq = { transactionStatus: () => (this.down ? 4 : 0), cmdTuples: () => '0', resultErrorFields: () => ({}) };
    }
    connectSync() { if (Flaky.refuse) throw new Error('connection refused'); }
    querySync(sql) {
      if (this.down) throw new Error('server closed the connection unexpectedly');
      return /to_regprocedure/.test(sql) ? [{ x: true }] : [{ client: this.n }];
    }
    end(cb) { setImmediate(cb); }
  }
  const log = console.error;
  console.error = () => {};
  try {
    const db = PostgresDatabase.open('postgres://db.example/x', { Client: Flaky, types: { getTypeParser: () => String } });
    clients[0].down = true;
    assert.equal(db.raw('SELECT 1 AS x')[0].client, 2); // a read: run again, on a new connection
    clients[1].down = true;
    assert.throws(() => db.raw('UPDATE t SET x = 1'), /server closed/); // a write may have been done: not run twice
    assert.equal(db.raw('UPDATE t SET x = 1')[0].client, 3); // the next query connects again
    assert.throws(() => db.transaction(() => { clients[2].down = true; return db.raw('SELECT 1'); }), /server closed/); // in a transaction: never again
    assert.equal(db.raw('SELECT 2')[0].client, 4);
    // The database is still down: connecting again fails, and the query after tries again.
    Flaky.refuse = true;
    clients[3].down = true;
    assert.throws(() => db.raw('SELECT 3'), /connection refused/);
    assert.throws(() => db.raw('SELECT 4'), /connection refused/);
    Flaky.refuse = false;
    assert.equal(db.raw('SELECT 5')[0].client, 7);
    await db.close();
  } finally {
    console.error = log;
  }
});

// --- against a real PostgreSQL -----------------------------------------------------------
let dir, db, store;
before(async () => {
  if (!onPostgres) return;
  dir = mkdtempSync(join(tmpdir(), 'html-server-pg-'));
  db = await testDatabase(dir);
  store = db.open();
});
after(async () => {
  if (!onPostgres) return;
  await db.drop();
  rmSync(dir, { recursive: true, force: true });
});

test('integers come back as numbers, and one JavaScript can\'t hold exactly is an error', { skip: live }, () => {
  assert.deepEqual(store.one('SELECT COUNT(*) AS n, 2 AS m, SUM(x) AS s FROM (SELECT 1 AS x UNION ALL SELECT 2) t'), { n: 1 + 1, m: 2, s: 3 });
  assert.throws(() => store.one('SELECT CAST(9007199254740993 AS BIGINT) AS big'), /too large for JavaScript/);
});

test('binary content comes back byte for byte; NUL in text is refused', { skip: live }, () => {
  const u = store.userForToken(store.createUser('bytes'));
  const doc = Buffer.from([0x3c, 0x70, 0x3e, 0x00, 0xff, 0xfe, 0x0a, 0x3c, 0x2f, 0x70, 0x3e]); // <p>, NUL, invalid UTF-8, </p>
  store.putVersion(u.id, 'raw.html', doc, { title: 'Raw' });
  assert.ok(store.version(store.find('raw.html'), 1).equals(doc));
  assert.throws(() => store.putVersion(u.id, 'nul.html', Buffer.from('<p>x</p>'), { title: 'a\0b' }), (e) => e.status === 400);
  assert.equal(store.find('nul.html'), undefined); // nothing half-written
});

test('nested transactions are savepoints: an inner failure rolls back only itself', { skip: live }, () => {
  store.tx(() => {
    store.setSetting('outer', '1');
    assert.throws(() => store.tx(() => { store.setSetting('inner', '1'); throw new Error('inner fails'); }), /inner fails/);
    store.setSetting('after', '1');
  });
  assert.deepEqual(['outer', 'inner', 'after'].map((k) => store.setting(k) ?? null), ['1', null, '1']);
  assert.throws(() => store.tx(() => { store.setSetting('rolled', '1'); throw new Error('outer fails'); }));
  assert.equal(store.setting('rolled'), undefined);
});

test('local days follow Node\'s time zone, even when it changes', { skip: live }, () => {
  const tz = process.env.TZ;
  try {
    const at = Date.UTC(2026, 0, 1, 3, 0) / 1000; // 03:00 UTC: still Dec 31 in Los Angeles
    for (const [zone, day] of [['UTC', '2026-01-01'], ['America/Los_Angeles', '2025-12-31']]) {
      process.env.TZ = zone;
      assert.equal(store.one("SELECT date(x.at, 'unixepoch', 'localtime') AS d FROM (SELECT ? + 0.0 AS at) x", at).d, day, zone);
    }
  } finally {
    if (tz === undefined) delete process.env.TZ; else process.env.TZ = tz;
  }
});

test('a closed connection says so, and closing twice is fine', { skip: live }, async () => {
  const other = PostgresDatabase.open(TEST_DATABASE_URL);
  await other.close();
  await other.close();
  assert.throws(() => other.raw('SELECT 1'), /connection is closed/);
});

test('the database ends this connection: the next query connects again', { skip: live }, async () => {
  const mine = PostgresDatabase.open(TEST_DATABASE_URL), killer = PostgresDatabase.open(TEST_DATABASE_URL);
  const log = console.error;
  console.error = () => {};
  try {
    const pid = mine.raw('SELECT pg_backend_pid() AS pid')[0].pid;
    killer.raw('SELECT pg_terminate_backend($1)', [pid]); // as a restart or a failover would
    assert.deepEqual(mine.raw('SELECT 1 AS x'), [{ x: 1 }]); // was: every query failed until the server restarted
    assert.notEqual(mine.raw('SELECT pg_backend_pid() AS pid')[0].pid, pid);
  } finally {
    console.error = log;
    await mine.close();
    await killer.close();
  }
});
